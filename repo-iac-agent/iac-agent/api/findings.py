"""
Drift findings: the CLI scanner (`python -m app.main scan`) submits them with the agent token; signed-in users review
and approve or reject them here. Held in memory: they are short-lived work items regenerated by every scan.
"""

import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Dict, List, Optional

from fastapi import APIRouter, Depends, Header, HTTPException
from pydantic import BaseModel, Field

from agentkit.auth import AuthUser, require_admin

from . import secrets as secrets_module

router = APIRouter(prefix="/ops", tags=["findings"])


class FindingStatus(str, Enum):
    pending_approval = "pending_approval"
    auto_applied = "auto_applied"
    approved = "approved"
    rejected = "rejected"
    applied = "applied"


class FindingCreate(BaseModel):
    type: str = "drift"
    resource: str
    summary: str
    risk_score: int = Field(..., ge=0, le=100)
    plan_diff: Optional[str] = None
    auto_apply: bool = False


class Finding(BaseModel):
    id: str
    type: str
    resource: str
    summary: str
    risk_score: int
    plan_diff: Optional[str] = None
    status: FindingStatus
    created_at: datetime
    decided_by: Optional[str] = None
    decided_at: Optional[datetime] = None
    applied_at: Optional[datetime] = None
    apply_result: Optional[str] = None


class ApplyResult(BaseModel):
    success: bool
    detail: str


_findings: Dict[str, Finding] = {}


def _agent(token: Optional[str]) -> None:
    expected = secrets_module.secrets.agent_api_token
    if expected and token != expected:
        raise HTTPException(401, "Invalid or missing X-Agent-Token")


@router.get("/findings", response_model=List[Finding])
async def list_findings(user: AuthUser = Depends(require_admin)):
    return sorted(_findings.values(), key=lambda f: f.created_at, reverse=True)


@router.post("/findings", response_model=Finding)
async def create_finding(p: FindingCreate, x_agent_token: Optional[str] = Header(default=None)):
    _agent(x_agent_token)
    now = datetime.now(timezone.utc)
    f = Finding(id=f"f-{uuid.uuid4().hex[:8]}", type=p.type, resource=p.resource, summary=p.summary, risk_score=p.risk_score, plan_diff=p.plan_diff,
                status=FindingStatus.auto_applied if p.auto_apply else FindingStatus.pending_approval, created_at=now,
                decided_by="policy-engine" if p.auto_apply else None, decided_at=now if p.auto_apply else None)
    _findings[f.id] = f
    return f


@router.get("/findings/awaiting-apply", response_model=List[Finding])
async def awaiting_apply(x_agent_token: Optional[str] = Header(default=None)):
    _agent(x_agent_token)
    return [f for f in _findings.values() if f.status == FindingStatus.approved]


def _decide(fid: str, approve: bool, who: str) -> Finding:
    f = _findings.get(fid)
    if not f:
        raise HTTPException(404, "Finding not found")
    if f.status != FindingStatus.pending_approval:
        raise HTTPException(409, f"Finding is already {f.status.value}")
    f.status = FindingStatus.approved if approve else FindingStatus.rejected
    f.decided_by, f.decided_at = who, datetime.now(timezone.utc)
    return f


@router.post("/findings/{fid}/approve", response_model=Finding)
async def approve(fid: str, user: AuthUser = Depends(require_admin)):
    return _decide(fid, True, user.email or user.id)


@router.post("/findings/{fid}/reject", response_model=Finding)
async def reject(fid: str, user: AuthUser = Depends(require_admin)):
    return _decide(fid, False, user.email or user.id)


@router.post("/findings/{fid}/apply-result", response_model=Finding)
async def apply_result(fid: str, r: ApplyResult, x_agent_token: Optional[str] = Header(default=None)):
    _agent(x_agent_token)
    f = _findings.get(fid)
    if not f:
        raise HTTPException(404, "Finding not found")
    f.status = FindingStatus.applied if r.success else f.status
    f.applied_at, f.apply_result = datetime.now(timezone.utc), r.detail
    return f
